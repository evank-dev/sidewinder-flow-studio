"""View as Python: each engine's work written out as plain lmfit/NumPy code.

The generated code is what a teacher would write on the board, and it must
produce the same output frame as the engine. Models are emitted with
`ParsedModel.source()`, the very text the engines compile and run, and guess
rules and helpers are copied verbatim, so the two can't drift apart.

The code runs in a pandas processor node: `df`, `dfs` and `pd` are provided.
"""
from __future__ import annotations

import re

from . import presets
from .evaluate import FROM_FIT, EvalError, resolve, split_inputs
from .expr import ExpressionError, parse_assignments
from .fit import GUESS_HELPERS, FitError, build_model


def _lit(v) -> str:
    """A Python literal for a parameter value."""
    return repr(float(v))


def _header(title: str) -> list[str]:
    return [f"# {title}", "# Generated by View as Python: the same work as the form, as code you can change.", ""]


# ── Curve fit ─────────────────────────────────────────────────────────────────

def fit_code(params: dict, inputs=None) -> str:
    p = params or {}
    x, y, y_err = p.get("x") or "", p.get("y") or "", p.get("y_err") or ""
    if not x or not y:
        raise FitError("Pick the x and y columns first")
    try:
        initial = parse_assignments(p.get("initial") or "")
    except ExpressionError as exc:
        raise FitError(str(exc)) from None
    spec = build_model(p.get("model") or "linear", p.get("expression") or "", p.get("variable") or "x")
    preset = presets.BY_ID.get(spec.preset, {})
    unknown = sorted(set(initial) - set(spec.params))
    if unknown:
        raise FitError(f"Initial guesses name unknown parameters: {', '.join(unknown)}")

    L = _header(f"Curve fit: {spec.expression}")
    L += ["import lmfit", "import numpy as np", ""]

    # data
    cols = [x, y] + ([y_err] if y_err else [])
    L += ["# ── the data ──",
          f"data = df[{cols!r}].astype(float)",
          "data = data[np.isfinite(data).all(axis=1)]   # drop rows with missing values",
          f"x = data[{x!r}].to_numpy()",
          f"y = data[{y!r}].to_numpy()"]
    if y_err:
        L += [f"err = data[{y_err!r}].to_numpy()   # the uncertainty of each y"]
    L += [""]

    # model and starting values
    L += ["# ── the model and its starting values ──"]
    if preset.get("lmfit"):
        cls_name, kwargs = preset["lmfit"]
        args = ", ".join(f"{k}={v!r}" for k, v in kwargs.items())
        L += [f"# {spec.expression}",
              f"model = lmfit.models.{cls_name}({args})"]
        if preset.get("guess_positive"):
            L += ["ok = (x > 0) & (y > 0)   # its guess takes logs: use the positive points",
                  "with np.errstate(all='ignore'):",
                  "    params = model.guess(y[ok], x=x[ok])"]
        else:
            L += ["params = model.guess(y, x=x)   # lmfit estimates starting values from the data"]
        for name in preset.get("free") or ():
            L += [f"params[{name!r}].set(expr='', vary=True)   # lmfit ties {name} by default; fit it too"]
    else:
        from .expr import parse
        parsed = parse(spec.expression, spec.variable)
        L += [parsed.source(name="f").rstrip(), "",
              f"model = lmfit.Model(f, independent_vars=[{spec.variable!r}])"]
        rules = preset.get("guess") or {}
        if rules:
            used = [h for h in GUESS_HELPERS if any(re.search(rf"\b{h}\(", r) for r in rules.values())]
            for h in used:
                L += ["", GUESS_HELPERS[h].rstrip()]
            L += ["", "# Starting values estimated from the data; one that fails becomes 1",
                  "with np.errstate(all='ignore'):", "    start = {"]
            L += [f"        {n!r}: {rule}," for n, rule in rules.items()]
            L += ["    }",
                  "start = {n: (v if np.isfinite(v) else 1.0) for n, v in start.items()}"]
            rest = [n for n in spec.params if n not in rules]
            if rest:
                L += ["start.update({" + ", ".join(f"{n!r}: 1.0" for n in rest) + "})"]
            L += ["params = model.make_params(**start)"]
        else:
            L += ["params = model.make_params("
                  + ", ".join(f"{n}=1.0" for n in spec.params) + ")   # every parameter starts at 1"]
    for n, v in initial.items():
        L += [f"params[{n!r}].set(value={_lit(v)})   # your initial guess"]
    L += [""]

    # fit
    var_kw = f"{spec.variable}=x"
    L += ["# ── fit ──"]
    if y_err:
        L += ["# Points are weighted by 1/σ, and with measured uncertainties the",
              "# parameter errors are absolute (not rescaled by the fit quality).",
              f"result = model.fit(y, params, {var_kw}, weights=1 / err, scale_covar=False)"]
    else:
        L += ["# No y errors: parameter errors are scaled by the reduced chi-square.",
              f"result = model.fit(y, params, {var_kw})"]
    L += ["if not result.success:",
          "    raise ValueError(f'Fit did not converge: {result.message}')",
          "# print(result.fit_report())   # the full report, in the run log",
          ""]

    # table
    model_rows = [("expression", spec.expression), ("variable", spec.variable),
                  ("preset", spec.preset), ("x_column", x), ("y_column", y), ("y_err_column", y_err)]
    L += ["# ── the result as one table: parameters, statistics, the model ──",
          "r_squared = 1 - np.sum((y - result.best_fit) ** 2) / np.sum((y - np.mean(y)) ** 2)",
          "",
          "def stderr(name):",
          "    s = result.params[name].stderr",
          "    return np.nan if s is None else s",
          "",
          "rows = [('parameter', n, result.params[n].value, stderr(n), '')",
          f"        for n in {spec.params!r}]",
          "rows += [('statistic', 'chi2', result.chisqr, np.nan, ''),",
          "         ('statistic', 'redchi', result.redchi, np.nan, ''),",
          "         ('statistic', 'r_squared', r_squared, np.nan, ''),",
          "         ('statistic', 'n_points', float(len(x)), np.nan, '')]",
          "rows += [('model', name, np.nan, np.nan, text) for name, text in ["]
    L += [f"    ({n!r}, {t!r})," for n, t in model_rows]
    L += ["]]",
          "df = pd.DataFrame(rows, columns=['kind', 'name', 'value', 'stderr', 'text'])"]
    return "\n".join(L) + "\n"


# ── Evaluate model ────────────────────────────────────────────────────────────

def eval_code(params: dict, inputs=None) -> str:
    p = params or {}
    frames = [f for f in (inputs or []) if f is not None]
    table, data_frames = split_inputs(frames)
    model = (p.get("model") or FROM_FIT).strip() or FROM_FIT
    if model == FROM_FIT and table is None:
        raise EvalError("Run the flow once first: the model comes from the connected Curve fit, "
                        "and View as Python reads it from the fit's last result")
    pm, values, preset, fit_x = resolve(table, model=model, expression=p.get("expression") or "",
                                        variable=p.get("variable") or "x",
                                        parameters=p.get("parameters") or "")
    mode = p.get("mode") or "range"
    from_table = table is not None
    if pm is None:
        names = _lmfit_names(preset)
        required = names
    elif mode == "range":
        names = required = pm.params
    else:  # columns: names with a value are parameters, the rest are columns
        names, required = [n for n in pm.args if n in values], []
    missing = [n for n in required if n not in values]
    if missing:
        raise EvalError(f"Missing parameter value{'s' if len(missing) > 1 else ''}: {', '.join(missing)}")

    title = pm.expression if pm is not None else preset.get("expression", "")
    L = _header(f"Evaluate model: {title}")
    L += ["import numpy as np"]
    if mode == "columns" and pm is not None:
        L += ["from uncertainties import unumpy as unp"]
    if pm is None:
        L += ["import lmfit"]
    L += [""]

    if from_table:
        L += ["# Inputs are told apart by their columns, never by their order",
              "def is_fit_table(f):",
              "    return {'kind', 'name', 'value', 'stderr'} <= set(f.columns)",
              "",
              "fit = next(f for f in dfs if is_fit_table(f))",
              "p = fit[fit['kind'] == 'parameter'].set_index('name')['value']   # fitted values",
              "# (their uncertainties are not propagated: that needs the covariance matrix)"]
        val = {n: f"p[{n!r}]" for n in names}
    else:
        L += ["p = {" + ", ".join(f"{n!r}: {_lit(values[n])}" for n in names) + "}   # parameter values"]
        val = {n: f"p[{n!r}]" for n in names}
    if mode == "columns":
        L += ["data = next(f for f in dfs if len(f.columns) > 0"
              + (" and not is_fit_table(f))" if from_table else ")")]
    L += [""]

    if pm is None:  # Voigt: lmfit evaluates it (no closed form)
        cls_name, kwargs = preset["lmfit"]
        L += ["# The Voigt profile has no closed form; lmfit evaluates it",
              f"model = lmfit.models.{cls_name}()",
              "params = model.make_params(" + ", ".join(f"{n}={val[n]}" for n in names) + ")"]
        L += [f"params[{n!r}].set(expr='')   # fitted on its own, not tied to sigma"
              for n in preset.get("free") or ()]
        L += [""]

    if mode == "range":
        start, stop, points = p.get("start"), p.get("stop"), p.get("points") or 200
        if start in (None, "") or stop in (None, ""):
            raise EvalError("Range mode needs Start and Stop")
        var = pm.variable if pm is not None else (preset.get("variable") or "x")
        out_col = fit_x or var
        if pm is not None:
            L += [pm.source().rstrip(), ""]
        L += [f"# The model over an even grid of {var}",
              f"{var} = np.linspace({_lit(start)}, {_lit(stop)}, {int(points)})"]
        if pm is None:
            L += [f"value = model.eval(params, x={var})"]
        else:
            call = ", ".join(([f"{var}={var}"] if var in pm.args else [])
                             + [f"{n}={val[n]}" for n in pm.params])
            L += [f"value = np.broadcast_to(model({call}), {var}.shape)"
                  if var not in pm.args else f"value = model({call})"]
        L += [f"df = pd.DataFrame({{{out_col!r}: {var}, 'value': value}})"]
        return "\n".join(L) + "\n"

    # columns
    output = (p.get("output") or "value").strip() or "value"
    var = pm.variable if pm is not None else (preset.get("variable") or "x")
    data_cols = set(map(str, data_frames[0].columns)) if data_frames else None
    x_col = (p.get("x") or "").strip()
    if not x_col and fit_x and (data_cols is None or fit_x in data_cols):
        x_col = fit_x
    x_col = x_col or var

    if pm is None:
        L += [f"df = data.copy()",
              f"df[{output!r}] = model.eval(params, x=data[{x_col!r}].to_numpy(float))"]
        return "\n".join(L) + "\n"

    from_cols = [n for n in pm.args if n not in names]
    col_of = {n: (x_col if n == var else n) for n in from_cols}
    L += ["def col(name):",
          "    \"\"\"A column as an array, with its uncertainty when there is a <name>_err column.\"\"\"",
          "    values = data[name].to_numpy(float)",
          "    if f'{name}_err' in data.columns:",
          "        return unp.uarray(values, np.nan_to_num(data[f'{name}_err'].to_numpy(float)))",
          "    return values",
          "",
          "# The model, with uncertainties' functions so errors propagate (first order)"]
    if "uabs(" in pm.unp_body:
        L += ["def uabs(u):",
              "    return np.where(unp.nominal_values(u) < 0, -u, u)   # abs() keeping the error",
              ""]
    L += [pm.source(pm.unp_body).rstrip(), ""]
    call = ", ".join(f"{n}={val[n]}" if n in names else f"{n}=col({col_of[n]!r})" for n in pm.args)
    if not from_cols:
        L += [f"value = np.broadcast_to(np.asarray(model({call}), dtype=object), (len(data),))"]
    else:
        L += [f"value = model({call})"]
    L += ["",
          "df = data.copy()",
          f"df[{output!r}] = unp.nominal_values(value).astype(float)",
          f"if any(f'{{c}}_err' in data.columns for c in {list(col_of.values())!r}):",
          f"    df[{output + '_err'!r}] = unp.std_devs(value).astype(float)"]
    return "\n".join(L) + "\n"


def _lmfit_names(preset: dict):
    import lmfit
    cls_name, kwargs = preset["lmfit"]
    m = getattr(lmfit.models, cls_name)(**kwargs)
    return list(m.param_names) + [n for n in preset.get("free") or () if n not in m.param_names]
